//! Taint tracking and propagation rules.
//!
//! Enforces Invariant 9:
//! Tainted data (web/file/voice/model) cannot silently become the targets or arguments
//! of a state-changing action without explicit user confirmation.
#![forbid(unsafe_code)]

use serde::{Deserialize, Serialize};
use std::collections::{BTreeMap, HashSet};

/// Source provenance taint labels.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum TaintLabel {
    /// Direct, trusted interactive user input from the local device keyboard.
    User,

    /// Data fetched from external web sources, HTTP responses, or scraping.
    Web,

    /// Data read from files, downloaded archives, or external storage.
    File,

    /// Data recognized from speech-to-text / acoustic input.
    Voice,

    /// Content generated by an LLM or planner.
    Model,
}

impl TaintLabel {
    /// Returns true if this taint is considered untrusted for autonomous execution.
    pub fn is_untrusted(&self) -> bool {
        match self {
            TaintLabel::User => false,
            TaintLabel::Web | TaintLabel::File | TaintLabel::Voice | TaintLabel::Model => true,
        }
    }
}

/// Map associating input argument names with their assigned taint labels.
#[derive(Debug, Clone, PartialEq, Eq, Default, Serialize, Deserialize)]
pub struct TaintMap {
    labels: BTreeMap<String, HashSet<TaintLabel>>,
}

impl TaintMap {
    pub fn new() -> Self {
        Self {
            labels: BTreeMap::new(),
        }
    }

    /// Adds a taint label to an argument name.
    pub fn insert_taint(&mut self, arg: &str, label: TaintLabel) {
        self.labels
            .entry(arg.to_string())
            .or_default()
            .insert(label);
    }

    /// Returns the set of taints associated with an argument.
    pub fn get_taints(&self, arg: &str) -> Option<&HashSet<TaintLabel>> {
        self.labels.get(arg)
    }

    /// Returns whether a specific argument carries any untrusted taint.
    pub fn has_untrusted_taint(&self, arg: &str) -> bool {
        if let Some(taints) = self.labels.get(arg) {
            taints.iter().any(|t| t.is_untrusted())
        } else {
            false
        }
    }

    /// Returns the first untrusted taint label found across all arguments, if any.
    pub fn first_untrusted_taint(&self) -> Option<(String, TaintLabel)> {
        for (arg, taints) in &self.labels {
            for taint in taints {
                if taint.is_untrusted() {
                    return Some((arg.clone(), *taint));
                }
            }
        }
        None
    }

    /// Returns whether any argument carries an untrusted taint.
    pub fn any_untrusted_taints(&self) -> bool {
        self.first_untrusted_taint().is_some()
    }
}
